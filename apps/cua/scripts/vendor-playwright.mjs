// Extracts Playwright's injected script from the pinned playwright-core into
// src/vendor/playwright-injected.ts. The browser engine installs it in pages for selectors,
// locators, accessibility snapshots, and form helpers.
//
//   node scripts/vendor-playwright.mjs
import { readFile, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const require = createRequire(join(root, "package.json"))
const packageDir = dirname(require.resolve("playwright-core/package.json"))
const { version } = JSON.parse(await readFile(join(packageDir, "package.json"), "utf8"))
const bundle = await readFile(join(packageDir, "lib", "coreBundle.js"), "utf8")

const MARKER = "// packages/playwright-core/src/generated/injectedScriptSource.ts"
const markerAt = bundle.indexOf(MARKER)
if (markerAt < 0) throw new Error(`playwright-core ${version}: injected script marker not found`)
const assignment = /\n\s+(source\d*) = '/u.exec(bundle.slice(markerAt))
if (!assignment) throw new Error(`playwright-core ${version}: injected script source not found`)
const start = markerAt + assignment.index + assignment[0].length - 1
let end = start + 1
while (bundle[end] !== "'") end += bundle[end] === "\\" ? 2 : 1
// The literal is a plain single-quoted JavaScript string.
const source = new Function(`return ${bundle.slice(start, end + 1)}`)()
if (!source.includes("InjectedScript: () => InjectedScript")) {
  throw new Error(`playwright-core ${version}: unexpected injected script shape`)
}

const output = `// Generated by scripts/vendor-playwright.mjs from playwright-core ${version}. Do not edit.
// Copyright (c) Microsoft Corporation. Licensed under the Apache License, Version 2.0.
// https://github.com/microsoft/playwright

export const PLAYWRIGHT_VERSION = ${JSON.stringify(version)}

/** The source of Playwright's injected script, a CommonJS module exporting \`InjectedScript\`. */
export const INJECTED_SCRIPT_SOURCE = ${JSON.stringify(source)}
`
await writeFile(join(root, "src", "vendor", "playwright-injected.ts"), output)
console.log(`Vendored the injected script of playwright-core ${version} (${source.length} bytes).`)
